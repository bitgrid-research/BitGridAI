"""Build the group allocation list of the study (between subjects, N = 16).

Each participant (VP01..VP16) is in exactly one group: A (colloquial hamster
texts) or B (technical). Permuted block randomisation, block size 4 (two A, two
B per block), so the groups stay balanced at every point of data collection
(8/8 at the end). Deterministic: the same seed always yields the same list, so
the allocation can be reproduced and checked from this script alone.

Output: src/ha/lab_only/lab_studie_liste.yaml (lab-only HA package, gitignored),
a template sensor whose attribute `liste` maps VP code -> group. The lab
dashboard "Sim-Steuerung" sets the group from it when the experimenter picks a
VP, so nobody chooses a group by hand.

Fix the list BEFORE the first session and do not regenerate it afterwards.

Usage: python scripts/build_randomisierung.py [--seed 20261017] [--print]
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

N_PARTICIPANTS = 16
BLOCK = ("A", "A", "B", "B")
DEFAULT_SEED = 20261017
OUT = Path(__file__).resolve().parent.parent / "src/ha/lab_only/lab_studie_liste.yaml"


def allocation(seed: int, n: int = N_PARTICIPANTS) -> dict[str, str]:
    """Return {VP code: group} by permuted blocks of size len(BLOCK)."""
    if n % len(BLOCK):
        raise ValueError(f"n={n} is not a multiple of the block size {len(BLOCK)}")
    rng = random.Random(seed)
    groups: list[str] = []
    for _ in range(n // len(BLOCK)):
        block = list(BLOCK)
        rng.shuffle(block)
        groups.extend(block)
    return {f"VP{i + 1:02d}": g for i, g in enumerate(groups)}


def render(seed: int, alloc: dict[str, str]) -> str:
    table = "\n".join(f"#   {vp}  {g}" for vp, g in alloc.items())
    counts = {g: list(alloc.values()).count(g) for g in sorted(set(BLOCK))}
    liste = json.dumps(alloc, ensure_ascii=False)
    return f"""\
# lab_studie_liste.yaml — LAB-ONLY group allocation of the study.
# GENERATED by scripts/build_randomisierung.py, do not edit by hand.
#
# Between subjects: every participant is in exactly one group.
# Method: permuted block randomisation, block size {len(BLOCK)} ({", ".join(BLOCK)}),
# random.Random(seed).shuffle per block. Seed: {seed}. Counts: {counts}.
# Fixed before the first session; regenerating it after data collection
# started would change the allocation.
#
{table}

lab_studie_liste:
  template:
    - sensor:
        - name: Lab Studie Randomisierung
          unique_id: lab_studie_randomisierung
          icon: mdi:shuffle-variant
          state: "{len(alloc)}"
          attributes:
            seed: "{seed}"
            methode: "Blockrandomisierung, Blockgroesse {len(BLOCK)}"
            liste: >-
              {{{{ {liste} }}}}
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", type=int, default=DEFAULT_SEED)
    ap.add_argument(
        "--print", action="store_true", help="print the list, write nothing"
    )
    args = ap.parse_args()
    alloc = allocation(args.seed)
    if args.print:
        for vp, g in alloc.items():
            print(vp, g)
        return 0
    OUT.write_text(render(args.seed, alloc), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(alloc)} VPs, seed {args.seed})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
